# deps.py <roster_data.inc> <out .inc>: for every actor in the roster, find the actors it creates at runtime (weapon items,
# props, effect volumes, heads) by walking its referenced configs, and write a C++ table of extra assets to preload.
# Why: Hammerhead's rifles and the Sable/Olympus jetpacks (a WeaponItemConfig too) showed as white cubes (2026-10-13):
# the enemy's own actor was loaded, but the weapon actor it spawns (via rifle_firing -> WeaponItem -> ItemActor) wasn't.
import io
import contextlib
import re
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ALERT"))   # clone Tkachov/ALERT into tools/ALERT
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import dat1lib
import dat1lib.crc64 as crc64
import extract

SKIP = ("masterpropconfig",)   # the global prop list: hundreds of cinematic props, not needed per enemy
MAX_DEPTH = 4


def norm(p):
    return p.replace("\\\\", "\\").replace("/", "\\").lower()


def main():
    roster, out = sys.argv[1], sys.argv[2]
    text = open(roster, encoding="utf-8").read()
    actors = sorted(set(norm(a) for a in re.findall(r'"([^"]+\.actor)"', text)))
    with contextlib.redirect_stdout(io.StringIO()):
        with open(extract.ARCHIVE + r"\toc", "rb") as f:
            toc = dat1lib.read(f)
        toc.set_archives_dir(extract.ARCHIVE)
    cache = {}

    def load(path):
        if path not in cache:
            e = toc.get_asset_entries_by_assetid(crc64.hash(path))
            cache[path] = toc.extract_asset(e[0]) if e else None
        return cache[path]

    def refs(data):
        found = set()
        for s in re.findall(rb"[\x20-\x7e]{6,}", data):
            s = s.decode()
            for m in re.findall(r"[A-Za-z0-9_\\/.\- ]+\.(?:actor|config)", s):
                found.add(norm(m))
        return found

    lines = []
    for actor in actors:
        data = load(actor)
        if data is None:
            print(f"MISSING {actor}")
            continue
        deps, seen = set(), {actor}
        frontier = [(r, 1) for r in refs(data)]
        while frontier:
            p, d = frontier.pop()
            if p in seen or any(k in p for k in SKIP):
                continue
            seen.add(p)
            sub = load(p)
            if sub is None:
                continue
            if p.endswith(".actor"):
                deps.add(p)
            if d < MAX_DEPTH and p.endswith(".config"):
                frontier += [(r, d + 1) for r in refs(sub)]
        deps.discard(actor)
        print(f"{actor}: {len(deps)}")
        for x in sorted(deps):
            print("   ", x)
        if deps:
            body = ", ".join('"' + x.replace("\\", "\\\\") + '"' for x in sorted(deps))
            lines.append(f'    {{ "{actor.replace(chr(92), chr(92) * 2)}", {{ {body} }} }},')
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/assets/deps.py from roster_data.inc: actors each roster actor creates at runtime.\n")
        f.write("// { actor, { extra actors to preload } }\n")
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
